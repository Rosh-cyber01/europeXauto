/* =========================================================
   CHANGE LANGUAGE
========================================================= */

function changeLanguage(language) {

    const dictionary =
        translations[language] ||
        translations.en;


    document.documentElement.lang =
        language;


    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.getAttribute("data-i18n");

            if (dictionary[key]) {

                element.textContent =
                    dictionary[key];

            }

        });

}


/* =========================================================
   GET URL PARAMETERS
========================================================= */

function getUrlParameter(name) {

    const params =
        new URLSearchParams(
            window.location.search
        );

    return params.get(name);

}


/* =========================================================
   LOAD LOCATION
========================================================= */

function loadLocationFromURL() {

    const city =
        getUrlParameter("location");

    const language =
        getUrlParameter("lang");


    if (city && locations[city]) {

        const location =
            locations[city];


        changeLanguage(
            language || location.language
        );


        document.title =
            `${location.name} Car Rental | Europe Car Rental`;

    } else {

        changeLanguage("en");

    }

}


/* =========================================================
   CITY / COUNTRY REDIRECTION
========================================================= */

function goToLocation(locationKey) {

    if (!locations[locationKey]) {
        return;
    }


    const location =
        locations[locationKey];


    const loading =
        document.getElementById(
            "loadingScreen"
        );


    loading.classList.add("active");


    /*
       700 milliseconds.

       This creates a smooth transition while
       remaining well below the requested 1–2 seconds.
    */

    setTimeout(() => {

        window.location.href =
            `index.html?location=${locationKey}&lang=${location.language}`;

    }, 700);

}


/* =========================================================
   LOCATION AUTOCOMPLETE
========================================================= */

const pickupInput =
    document.getElementById(
        "pickupLocation"
    );

const dropoffInput =
    document.getElementById(
        "dropoffLocation"
    );

const pickupSuggestions =
    document.getElementById(
        "pickupSuggestions"
    );

const dropoffSuggestions =
    document.getElementById(
        "dropoffSuggestions"
    );


function createSuggestions(
    input,
    suggestionBox
) {

    input.addEventListener(
        "input",
        function () {

            const search =
                this.value
                    .trim()
                    .toLowerCase();


            suggestionBox.innerHTML = "";


            if (!search) {

                suggestionBox.style.display =
                    "none";

                return;

            }


            const results =
                Object.entries(locations)
                    .filter(([key, location]) => {

                        return (

                            location.name
                                .toLowerCase()
                                .includes(search)

                            ||

                            location.country
                                .toLowerCase()
                                .includes(search)

                        );

                    })
                    .slice(0, 8);


            if (!results.length) {

                suggestionBox.style.display =
                    "none";

                return;

            }


            results.forEach(
                ([key, location]) => {

                    const div =
                        document.createElement("div");


                    div.className =
                        "suggestion";


                    div.innerHTML = `

                        <strong>
                            ${location.name}
                        </strong>

                        <small>
                            ${location.country}
                            · From €${location.price}/day
                        </small>

                    `;


                    div.addEventListener(
                        "click",
                        function () {

                            input.value =
                                location.name;

                            suggestionBox.style.display =
                                "none";

                        }
                    );


                    suggestionBox.appendChild(div);

                }
            );


            suggestionBox.style.display =
                "block";

        }
    );

}


createSuggestions(
    pickupInput,
    pickupSuggestions
);

createSuggestions(
    dropoffInput,
    dropoffSuggestions
);


/* =========================================================
   CLOSE SUGGESTIONS WHEN CLICKING OUTSIDE
========================================================= */

document.addEventListener(
    "click",
    function (event) {

        if (
            !pickupInput.contains(event.target) &&
            !pickupSuggestions.contains(event.target)
        ) {

            pickupSuggestions.style.display =
                "none";

        }


        if (
            !dropoffInput.contains(event.target) &&
            !dropoffSuggestions.contains(event.target)
        ) {

            dropoffSuggestions.style.display =
                "none";

        }

    }
);


