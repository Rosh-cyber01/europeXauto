    new Date(today);

tomorrow.setDate(
    today.getDate() + 1
);


const nextWeek =
    new Date(today);

nextWeek.setDate(
    today.getDate() + 8
);


function formatDate(date) {

    return date
        .toISOString()
        .split("T")[0];

}


pickupDate.value =
    formatDate(tomorrow);

returnDate.value =
    formatDate(nextWeek);


/* =========================================================
   SEARCH BUTTON
========================================================= */

document
    .getElementById("searchButton")
    .addEventListener(
        "click",
        function () {

            const pickup =
                pickupInput.value.trim();

            const dropoff =
                dropoffInput.value.trim();

            const pickupDateValue =
                pickupDate.value;

            const returnDateValue =
                returnDate.value;


            if (!pickup) {

                alert(
                    "Please select a pick-up location."
                );

                pickupInput.focus();

                return;

            }


            if (!pickupDateValue ||
                !returnDateValue) {

                alert(
                    "Please select your rental dates."
                );

                return;

            }


            if (
                new Date(returnDateValue)
                <=
                new Date(pickupDateValue)
            ) {

                alert(
                    "Return date must be after the pick-up date."
                );

                return;

            }


            /*
               For now this creates a search URL.

               Later we can connect this to
               your actual rental inventory.
            */

            const params =
                new URLSearchParams({

                    pickup: pickup,

                    dropoff:
                        dropoff || pickup,

                    pickupDate:
                        pickupDateValue,

                    returnDate:
                        returnDateValue,

                    driverAge:
                        document.getElementById(
                            "driverAge"
                        ).value

                });


            window.location.href =
                `results.html?${params.toString()}`;

        }
    );


/* =========================================================
   NEWSLETTER
========================================================= */

document
    .getElementById("subscribeButton")
    .addEventListener(
        "click",
        function () {

            const email =
                document
                    .getElementById(
                        "emailInput"
                    )
                    .value
                    .trim();


            if (!email) {

                alert(
                    "Please enter your email address."
                );

                return;

            }


            if (
                !email.includes("@")
            ) {

                alert(
                    "Please enter a valid email address."
                );

                return;

            }


            alert(
                "Thank you! You have been subscribed."
            );

        }
    );


